 public static int nativeKey(int key) { return TO_NATIVE.getOrDefault(key, -1); }
 public static int legacyKey(int key) { return TO_LEGACY.getOrDefault(key, -1); }
 public static int legacyModifiers(int modifiers) {
  return ((modifiers & InputConstants.MOD_SHIFT)!=0?1:0) | ((modifiers & InputConstants.MOD_CONTROL)!=0?2:0) | ((modifiers & InputConstants.MOD_ALT)!=0?4:0) | ((modifiers & InputConstants.MOD_SUPER)!=0?8:0);
 }
 public static int legacyMouseButton(int button) { return button==1?0:button==3?1:button==2?2:button-1; }
 public static int keyState(long window, int key) { int nativeCode=nativeKey(key); return nativeCode>=0 && InputConstants.isKeyDown(nativeCode)?PRESS:RELEASE; }
 public static String keyName(int key,int unused) { int nativeCode=nativeKey(key); return nativeCode<0?null:InputConstants.Type.KEYBOARD.getOrCreate(nativeCode).getDisplayName().getString(); }
 public static int mouseButtonState(long window,int button) { int nativeButton=button==0?1:button==1?3:button==2?2:button+1; return (SDLMouse.SDL_GetMouseState(null,null) & (1 << (nativeButton-1)))!=0?PRESS:RELEASE; }
 public static void cursorPosition(long window,double[] x,double[] y) { x[0]=Minecraft.getInstance().mouseHandler.xpos(); y[0]=Minecraft.getInstance().mouseHandler.ypos(); }
 public static void setCursorPosition(long window,double x,double y) { SDLMouse.SDL_WarpMouseInWindow(window,(float)x,(float)y); }
